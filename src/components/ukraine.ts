const LON0 = 22, LAT0 = 52.6, SCALE = 74, KX = Math.cos((48.3 * Math.PI) / 180);
export const MAP_W = Math.round((40.4 - LON0) * KX * SCALE);
export const MAP_H = Math.round((LAT0 - 44.2) * SCALE);
export const project = (lon: number, lat: number) => ({
  x: (lon - LON0) * KX * SCALE,
  y: (LAT0 - lat) * SCALE,
});
export const outlinePath = () =>
  UKRAINE_OUTLINE.map(([lon, lat], i) => {
    const { x, y } = project(lon, lat);
    return `${i ? "L" : "M"}${x.toFixed(1)} ${y.toFixed(1)}`;
  }).join(" ") + " Z";
